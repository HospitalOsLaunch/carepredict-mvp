#!/usr/bin/env python3
"""HOWM-INT-1 scientific archive (decision n.9).

    package_int1.py NAME

Contents (verified in a fresh directory after zipping):
  source_tree.tar.gz        git archive HEAD (src, scripts, tests, docs, evidence/howm_int1 incl. ledger, results, manifests)
  data/int1_runs/...        every run of the campaign: best checkpoints, configurations, normalisations, curves, results,
                            D pickles (training-state files last.pt are NOT packaged: optimiser state, not needed to load)
  data/int1_eval/...        every final-evaluation file (MAIN, SUB32, EXT, COMBO, SIZE12)
  data/int1_corpus/INT_VAL  the VAL corpus (300 structures)
  data/int1_corpus/INT_TRAIN tier 1 (structures 0-999) + the tier-2 samples used by the receipt; the rest of tier 2 is
                            described by MANIFEST_CORPUS.json (per-file SHA-256) and regenerable by corpus.py
  requirements_frozen.txt   the venv package list (pip freeze; SHA-256 recorded in the ledger)
  RESTORE.md, SHA256SUMS
Refuses to run with uncommitted changes in src/scripts/tests/docs/howm_int1."""

import hashlib
import json
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
S = Path("/tmp/claude-0/-home-user-carepredict-mvp/766fa6b7-33a5-533f-a444-71f97217a53a/scratchpad")
OUT = S / "int1_packages"
TIER2_SAMPLES = (9001,)  # tier-2 corpus files regenerated by the receipt (originals packaged for comparison)


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def main() -> int:
    name = sys.argv[1]
    dirty = subprocess.run(["git", "status", "--porcelain", "--", "src", "scripts", "tests", "docs/howm_int1"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    if dirty:
        raise SystemExit("uncommitted source changes:\n" + dirty)
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    OUT.mkdir(parents=True, exist_ok=True)
    st = Path(tempfile.mkdtemp(prefix="pkgint1_", dir=OUT))
    subprocess.run(["git", "archive", "--format=tar.gz", "-o", str(st / "source_tree.tar.gz"), "HEAD"], cwd=ROOT, check=True)
    d = st / "data"
    shutil.copytree(S / "int1_runs", d / "int1_runs", ignore=shutil.ignore_patterns("last.pt"))
    shutil.copytree(S / "int1_eval", d / "int1_eval", ignore=shutil.ignore_patterns("*.tmp"))
    shutil.copytree(S / "int1_corpus/INT_VAL", d / "int1_corpus/INT_VAL")
    (d / "int1_corpus/INT_TRAIN").mkdir(parents=True)
    for s in list(range(1000)) + list(TIER2_SAMPLES):
        for ext in (".npz", ".json"):
            shutil.copy(S / "int1_corpus/INT_TRAIN" / f"s{s:05d}{ext}", d / "int1_corpus/INT_TRAIN" / f"s{s:05d}{ext}")
    shutil.copy(ROOT / "evidence/howm1/venv_howm_freeze.txt", st / "requirements_frozen.txt")
    fr = json.loads((ROOT / "evidence/howm_int1/FREEZE_INT1.json").read_text())
    bad_models = [k for k, h in fr["models_sha256"].items() if sha(d / k) != h]
    if bad_models:
        raise SystemExit(f"frozen model hash mismatch: {bad_models}")
    (st / "RESTORE.md").write_text(f"""# HOWM-INT-1 archive {name} (decision n.9)

Commit {head}. Statuses: PROTOTYPE_UNVALIDATED, clinical_validation=false, G2=NO-GO.

1. `sha256sum -c SHA256SUMS`
2. `mkdir tree && tar -xzf source_tree.tar.gz -C tree`
3. Python 3.11.18; `python -m venv v && v/bin/pip install --extra-index-url https://download.pytorch.org/whl/cpu -r requirements_frozen.txt`
   (torch 2.15.0+cpu, scikit-learn 1.8.0, numpy 2.4.6)
4. Data: the scripts read `/tmp/claude-0/-home-user-carepredict-mvp/766fa6b7-33a5-533f-a444-71f97217a53a/scratchpad/{{int1_runs,int1_eval,int1_corpus}}`;
   copy `data/*` there, or override the module globals `S`/`OUT`/`RUNS`/`CORPUS` as `scripts/int1/restore_int1.py` does.
5. Tests: `python -m pytest tests/howm_int1`
6. Frozen analysis: `python scripts/int1/analyse.py` -> evidence/howm_int1/RESULTS_INT1.json; post-hoc tables: `python scripts/int1/posthoc_main.py`
7. One final-evaluation file: `python scripts/int1/eval_campaign.py --panel MAIN --s0 s --s1 s+1 --par 1` (SUB32: one job per future)
8. One corpus structure: `python scripts/int1/corpus.py --part INT_TRAIN --s0 s --s1 s+1 --par 1 --out DIR` (VAL: `--K 4`)
9. Demonstration: `python scripts/int1/demo.py`
10. Receipt in a fresh environment: `python scripts/int1/restore_int1.py <section> <archive.zip> <python>` (see the script)
""")
    files = sorted(p for p in st.rglob("*") if p.is_file())
    (st / "SHA256SUMS").write_text("".join(f"{sha(p)}  {p.relative_to(st)}\n" for p in files))
    z = OUT / f"HOWM_INT1_{name}.zip"
    with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(st.rglob("*")):
            if p.is_file():
                zf.write(p, p.relative_to(st))
    shutil.rmtree(st)
    fresh = Path(tempfile.mkdtemp(prefix="vint1_", dir=OUT))
    with zipfile.ZipFile(z) as zf:
        zf.extractall(fresh)
    bad = [rel for h, rel in (ln.split("  ", 1) for ln in (fresh / "SHA256SUMS").read_text().splitlines()) if sha(fresh / rel) != h]
    shutil.rmtree(fresh)
    res = {"package": z.name, "sha256": sha(z), "bytes": z.stat().st_size, "head": head, "files": len(files), "bad": bad,
           "frozen_models_hash_ok": True, "eval_files": {p: len(list((S / "int1_eval" / p).glob("*.json"))) for p in ("MAIN", "SUB32", "EXT", "COMBO", "SIZE12")}}
    rec = ROOT / "evidence/howm_int1_receipt"
    rec.mkdir(exist_ok=True)
    (rec / f"PACKAGE_{name}.json").write_text(json.dumps(res, indent=1) + "\n")
    print(json.dumps(res))
    return 0 if not bad else 1


if __name__ == "__main__":
    raise SystemExit(main())
